-- Security tests for the social feed (supabase/migrations/20261106000000_social.sql).
--
-- Impersonates three users (A, B, C) by switching to the `authenticated` role and
-- setting JWT claims, exactly as PostgREST does for a real request, then checks
-- what each one can read and write.
--
-- Run after applying the migration: paste into the Supabase SQL editor, or
--   psql "$DATABASE_URL" -f supabase/tests/social_rls.sql
-- Everything runs in one transaction that is rolled back, so no data is left
-- behind. Each passing check emits NOTICE "ok - ..."; the first failure aborts
-- with "FAIL: ...". A clean run in the SQL editor shows "Success. No rows returned".

begin;

-- Helpers ---------------------------------------------------------------------

create function pg_temp.login(uid uuid) returns void
language plpgsql as $$
begin
  perform set_config('role', 'authenticated', true);
  perform set_config('request.jwt.claims',
    json_build_object('sub', uid, 'role', 'authenticated')::text, true);
end;
$$;

create function pg_temp.check(passed boolean, description text) returns void
language plpgsql as $$
begin
  if passed is not true then
    raise exception 'FAIL: %', description;
  end if;
  raise notice 'ok - %', description;
end;
$$;

-- Runs a statement that must fail with the given SQLSTATE.
--   42501 insufficient privilege / RLS violation
--   23505 unique violation, 23514 check violation
create function pg_temp.check_denied(statement text, expected_state text, description text)
returns void
language plpgsql as $$
begin
  execute statement;
  raise exception 'FAIL: % (statement succeeded)', description;
exception
  when others then
    if sqlerrm like 'FAIL:%' then
      raise;
    end if;
    if sqlstate <> expected_state then
      raise exception 'FAIL: % (got % "%", expected %)', description, sqlstate, sqlerrm, expected_state;
    end if;
    raise notice 'ok - %', description;
end;
$$;

-- Fixtures --------------------------------------------------------------------
-- A = 0a (author), B = 0b (follower), C = 0c (outsider)

insert into auth.users (id, email, aud, role) values
  ('00000000-0000-4000-8000-00000000000a', 'a@test.local', 'authenticated', 'authenticated'),
  ('00000000-0000-4000-8000-00000000000b', 'b@test.local', 'authenticated', 'authenticated'),
  ('00000000-0000-4000-8000-00000000000c', 'c@test.local', 'authenticated', 'authenticated');

-- Usernames -------------------------------------------------------------------

select pg_temp.login('00000000-0000-4000-8000-00000000000a');
insert into public.usernames (username) values ('alice');
insert into public.profiles (name, updated_at) values ('Alice', now());
select pg_temp.check(
  (select username from public.usernames where user_id = '00000000-0000-4000-8000-00000000000a') = 'alice',
  'A claims @alice');

select pg_temp.login('00000000-0000-4000-8000-00000000000b');
select pg_temp.check_denied(
  $$insert into public.usernames (username) values ('alice')$$,
  '23505', 'B cannot take a username that is already claimed');
select pg_temp.check_denied(
  $$insert into public.usernames (user_id, username)
    values ('00000000-0000-4000-8000-00000000000c', 'carol')$$,
  '42501', 'B cannot claim a username on behalf of C');
insert into public.usernames (username) values ('bob');

update public.usernames set username = 'hacked'
  where user_id = '00000000-0000-4000-8000-00000000000a';
select pg_temp.check(
  (select username from public.usernames where user_id = '00000000-0000-4000-8000-00000000000a') = 'alice',
  'B cannot rename A''s username');

select pg_temp.login('00000000-0000-4000-8000-00000000000c');
select pg_temp.check_denied(
  $$insert into public.usernames (username) values ('Bad Name!')$$,
  '23514', 'Usernames must be 3-20 lowercase letters, digits or _');
insert into public.usernames (username) values ('carol');

-- Activity is generated by the server ---------------------------------------------

select pg_temp.login('00000000-0000-4000-8000-00000000000a');
insert into public.items (sync_id, title, media_type, status, date_added, updated_at) values
  ('10000000-0000-4000-8000-000000000001', 'Frieren', 'anime', 'planning', now()::text, now()),
  ('10000000-0000-4000-8000-000000000002', 'Old Book', 'book', 'completed', now()::text,
   now() - interval '30 days');

select pg_temp.check(
  (select count(*) from public.activities) = 1
  and exists (select 1 from public.activities where kind = 'added' and status = 'planning'),
  'Adding an item records one "added" activity; a 30-day-old edit syncing late does not');

select pg_temp.check_denied(
  $$insert into public.activities (user_id, item_sync_id, kind, status, title, media_type)
    values (auth.uid(), '10000000-0000-4000-8000-000000000001', 'status', 'completed', 'Fake', 'anime')$$,
  '42501', 'Clients cannot insert activity directly');
select pg_temp.check_denied(
  $$update public.activities set title = 'Edited'$$,
  '42501', 'Clients cannot edit activity');

update public.items set status = 'in_progress', updated_at = now() + interval '1 minute'
  where sync_id = '10000000-0000-4000-8000-000000000001';
select pg_temp.check(
  (select count(*) from public.activities) = 1,
  'Moving to In Progress posts nothing');

update public.items set status = 'completed', updated_at = now() + interval '2 minutes'
  where sync_id = '10000000-0000-4000-8000-000000000001';
select pg_temp.check(
  exists (select 1 from public.activities where kind = 'status' and status = 'completed'),
  'Completing an item posts a status activity');

update public.items set status = 'dropped', updated_at = now() + interval '3 minutes'
  where sync_id = '10000000-0000-4000-8000-000000000001';
select pg_temp.check(
  (select array_agg(status order by status) from public.activities where kind = 'status')
    = array['completed', 'dropped'],
  'Each status change gets its own activity (completed, then dropped, shows both)');

-- Older than the stored row, so the last-write-wins trigger skips it.
update public.items set status = 'completed', updated_at = now()
  where sync_id = '10000000-0000-4000-8000-000000000001';
select pg_temp.check(
  (select count(*) from public.activities where kind = 'status') = 2,
  'A stale (skipped) sync posts nothing');

reset role;
select set_config('test.activity_id',
  (select id::text from public.activities
   where item_sync_id = '10000000-0000-4000-8000-000000000001' and kind = 'added'),
  true);

-- Follows gate visibility ------------------------------------------------------------

select pg_temp.login('00000000-0000-4000-8000-00000000000b');
select pg_temp.check(
  (select count(*) from public.activities) = 0
  and (select count(*) from public.get_feed()) = 0,
  'B cannot see A''s activity before following');
select pg_temp.check_denied(
  $$insert into public.activity_likes (activity_id)
    values (current_setting('test.activity_id')::bigint)$$,
  '42501', 'B cannot like an activity it cannot see');
select pg_temp.check_denied(
  $$insert into public.follows (follower_id, followee_id)
    values ('00000000-0000-4000-8000-00000000000c', '00000000-0000-4000-8000-00000000000a')$$,
  '42501', 'B cannot make C follow someone');
select pg_temp.check_denied(
  $$insert into public.follows (followee_id) values ('00000000-0000-4000-8000-00000000000b')$$,
  '23514', 'No self-follows');

insert into public.follows (followee_id) values ('00000000-0000-4000-8000-00000000000a');
select pg_temp.check(
  (select count(*) from public.get_feed()) = 3,
  'B sees A''s activity after following');
select pg_temp.check(
  (select count(*) from public.items) = 0,
  'Following does not expose the author''s library rows');
select pg_temp.check(
  (select name from public.profiles where user_id = '00000000-0000-4000-8000-00000000000a') = 'Alice',
  'B can read A''s profile');
update public.profiles set name = 'Hacked'
  where user_id = '00000000-0000-4000-8000-00000000000a';
select pg_temp.check(
  (select name from public.profiles where user_id = '00000000-0000-4000-8000-00000000000a') = 'Alice',
  'B cannot edit A''s profile');

insert into public.activity_likes (activity_id) values (current_setting('test.activity_id')::bigint);
select pg_temp.check(
  (select liked and like_count = 1 from public.get_feed()
   where id = current_setting('test.activity_id')::bigint),
  'get_feed reports B''s like');
select pg_temp.check_denied(
  $$insert into public.activity_likes (activity_id, user_id)
    values (current_setting('test.activity_id')::bigint, '00000000-0000-4000-8000-00000000000c')$$,
  '42501', 'B cannot like on behalf of C');

-- B can see A's activity but deleting it matches no rows.
delete from public.activities;
select pg_temp.check(
  (select count(*) from public.get_feed()) = 3,
  'B cannot delete A''s activity');

select pg_temp.check(
  (select count(*) from public.search_users('al') where username = 'alice' and is_following) = 1,
  'search_users finds @alice and reports the follow');
select pg_temp.check(
  (select count(*) from public.search_users('_')) = 0,
  'search_users treats _ literally, not as a wildcard');
select pg_temp.check(
  (select follower_count = 1 and is_following
   from public.get_public_profile('00000000-0000-4000-8000-00000000000a')),
  'get_public_profile counts followers');

select pg_temp.login('00000000-0000-4000-8000-00000000000c');
select pg_temp.check(
  (select count(*) from public.activity_likes) = 0
  and (select count(*) from public.get_feed()) = 0,
  'C (not following) sees neither A''s activity nor the likes on it');
delete from public.follows where follower_id = '00000000-0000-4000-8000-00000000000b';
delete from public.activity_likes;

select pg_temp.login('00000000-0000-4000-8000-00000000000b');
select pg_temp.check(
  (select count(*) from public.follows where follower_id = auth.uid()) = 1
  and (select count(*) from public.activity_likes) = 1,
  'C cannot remove B''s follow or like');

-- Feed scopes ---------------------------------------------------------------------

select pg_temp.login('00000000-0000-4000-8000-00000000000a');
select pg_temp.check(
  (select count(*) from public.get_feed()) = 3
  and (select count(*) from public.get_feed(following_only => true)) = 0,
  'A sees own activity; following_only hides it');

-- Deleting and unfollowing ------------------------------------------------------------

-- A deletes one of their own entries; it's gone for B too, and the item stays.
delete from public.activities
  where item_sync_id = '10000000-0000-4000-8000-000000000001' and status = 'completed';
select pg_temp.check(
  (select count(*) from public.get_feed()) = 2
  and (select count(*) from public.items where sync_id = '10000000-0000-4000-8000-000000000001') = 1,
  'A can delete own activity without touching the library item');
select pg_temp.login('00000000-0000-4000-8000-00000000000b');
select pg_temp.check(
  (select count(*) from public.get_feed()) = 2,
  'A''s deleted activity is gone from B''s feed');
select pg_temp.login('00000000-0000-4000-8000-00000000000a');

update public.items set deleted_at = now() + interval '4 minutes', updated_at = now() + interval '4 minutes'
  where sync_id = '10000000-0000-4000-8000-000000000001';
reset role;
select pg_temp.check(
  (select count(*) from public.activities
   where item_sync_id = '10000000-0000-4000-8000-000000000001') = 0
  and (select count(*) from public.activity_likes) = 0,
  'Deleting an item removes its activity and likes');

select pg_temp.login('00000000-0000-4000-8000-00000000000a');
insert into public.items (sync_id, title, media_type, status, date_added, updated_at) values
  ('10000000-0000-4000-8000-000000000003', 'Hades', 'game', 'completed', now()::text, now());

select pg_temp.login('00000000-0000-4000-8000-00000000000b');
select pg_temp.check((select count(*) from public.get_feed()) = 1, 'B sees A''s new activity');
delete from public.follows where followee_id = '00000000-0000-4000-8000-00000000000a';
select pg_temp.check((select count(*) from public.get_feed()) = 0, 'Unfollowing hides A''s activity again');

-- Signed out --------------------------------------------------------------------------

reset role;
set local role anon;
select pg_temp.check_denied($$select * from public.activities$$, '42501', 'anon cannot read activities');
select pg_temp.check_denied($$select * from public.follows$$, '42501', 'anon cannot read follows');
select pg_temp.check_denied($$select * from public.get_feed()$$, '42501', 'anon cannot call get_feed');
reset role;

rollback;
